export function t(lang: LanguageCode, key: StringKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function translator(lang: LanguageCode) {
  return (key: StringKey, vars?: Record<string, string | number>) => t(lang, key, vars);
}
